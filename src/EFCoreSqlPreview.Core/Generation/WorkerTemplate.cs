namespace EFCoreSqlPreview.Core.Generation;

/// <summary>
/// The fixed harness the generated worker is built from: the capture interceptor, the synthetic-row reader,
/// the DbContext activation ladder and the JSON output protocol.
/// </summary>
/// <remarks>
/// <para>
/// The template is a plain string rather than an embedded resource so the netstandard2.0 assembly needs no
/// resource lookup and the text is diffable in source control.
/// </para>
/// <para>
/// Several properties of this text were established empirically and must not be "tidied":
/// <c>FieldCount</c> is 1024 because a narrower reader fails split queries with "the underlying reader doesn't
/// have as many fields as expected" and <c>int.MaxValue</c> throws <c>OutOfMemoryException</c>; the reader
/// yields exactly one synthetic row because a zero-row reader makes every aggregate terminal throw; and
/// <c>PublishAot=false</c> is required or EF refuses to build the model at all.
/// </para>
/// </remarks>
public static class WorkerTemplate
{
