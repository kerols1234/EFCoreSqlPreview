    public const string ContextTypePlaceholder = "{{CONTEXT_TYPE}}";

    /// <summary>Placeholder for the type the activated context is cast to before the query runs.</summary>
    public const string ContextCastTypePlaceholder = "{{CONTEXT_CAST_TYPE}}";

    /// <summary>Placeholder for the free-variable declarations and replayed statements.</summary>
    public const string FreeVariablesPlaceholder = "{{FREE_VARIABLES}}";

    /// <summary>Placeholder for the <c>Observe*</c> call wrapping the user's query.</summary>
    public const string ObserveCallPlaceholder = "{{OBSERVE_CALL}}";

    /// <summary>Placeholder for the generated <c>OnConfiguring</c> subclass, empty when it is not needed.</summary>
