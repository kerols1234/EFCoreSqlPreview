public static class Preview
{
    public const string Begin = "<<<EFSQLPREVIEW-BEGIN>>>";
    public const string End = "<<<EFSQLPREVIEW-END>>>";

    // Deliberately not const: a const null would make the dialect checks compile-time constants and every
    // branch behind them unreachable code, which litters stdout with CS0162 next to the payload.
    public static readonly string Dialect = {{DIALECT}};
    public const string Neutral = {{CONNECTION_STRING}};

    public static void ConfigureProvider(DbContextOptionsBuilder b) => {{PROVIDER_CONFIG}};

    public static void Emit(Report report)
    {
        try { Console.OutputEncoding = Encoding.UTF8; } catch { }
        var json = JsonSerializer.Serialize(report, new JsonSerializerOptions
        {
            WriteIndented = false,
            Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        });
        Console.Out.Write(Begin);
        Console.Out.Write(json);
        Console.Out.Write(End);
        Console.Out.WriteLine();
        Console.Out.Flush();
    }

    public static async Task<Report> RunAsync(Type contextType, Func<DbContext, Probe, Task<ResultInfo>> body)
    {
        var report = new Report { contextType = contextType.FullName };

        // Rung 1 materializes a synthetic row, which is what stops aggregate terminals throwing and lets a
        // split query issue all of its commands. Rung 2 feeds a real discriminator value for TPH models.
        // Rung 3 gives up on materialization and always runs, at the cost of partial split-query capture.
        var rungs = new[]
        {
            new Rung("SyntheticRow", 1, ""),
            new Rung("SyntheticRowTph", 1, null),
            new Rung("NoRows", 0, ""),
        };

        Attempt best = null;
        foreach (var rung in rungs)
        {
            var attempt = new Attempt { rung = rung.Name };
            var probe = new Probe { Rows = rung.Rows, StringValue = rung.StringValue };
            var interceptor = new CaptureInterceptor(probe);
            DbContext ctx = null;
            try
            {
                ctx = ContextActivator.Create(contextType, interceptor, report);
                if (rung.StringValue == null)
                {
                    var discriminator = FirstDiscriminatorValue(ctx);
                    if (discriminator == null) continue;
                    probe.StringValue = discriminator;
                }

                report.provider = ProviderShortName(ctx.Database.ProviderName);
                report.providerAssembly = ctx.Database.ProviderName;
                report.connectionString = Sanitize(ctx.Database.GetConnectionString());
                probe.Model = ctx.Model;
                attempt.result = await body(ctx, probe);
            }
            catch (PreviewActivationException activationFailure)
            {
                attempt.error = activationFailure.Message;
                attempt.errorKind = "ContextActivationFailed";
                attempt.commands = probe.Captured;
                best = attempt;
                break;
            }
            catch (Exception ex)
            {
                var unwrapped = Unwrap(ex);
                attempt.error = unwrapped.GetType().Name + ": " + unwrapped.Message;
                attempt.errorKind = Classify(unwrapped);
                attempt.detail = Detail(unwrapped);
            }
            finally
            {
                try { ctx?.Dispose(); } catch { }
            }

            attempt.commands = probe.Captured;
            if (best == null
                || attempt.commands.Count > best.commands.Count
                || (attempt.commands.Count == best.commands.Count && best.error != null && attempt.error == null))
            {
                best = attempt;
            }

            if (attempt.error == null && attempt.commands.Count > 0) break;
        }

        report.commands = best.commands;
        report.result = best.result;
        report.captureMode = best.rung;

        // Capturing at least one command is the definition of success: aggregate terminals and hostile
        // mappings can still throw afterwards, long after the SQL the user asked for was fully built.
        report.success = best.commands.Count > 0;

        if (!report.success)
        {
            report.error = best.error ?? "The query produced no SQL command.";
            report.errorKind = best.errorKind ?? "Unknown";
        }
        else
        {
            if (best.rung == "NoRows")
            {
                report.warnings.Add(
                    "This model could not materialize a synthetic row (a TPH discriminator or a JSON-mapped owned entity), "
                    + "so the query ran against an empty result set. If it is a split query, only the first of its commands is shown.");
            }

            if (best.error != null)
            {
                report.warnings.Add("SQL was captured, but the run ended with: " + best.error
                    + (best.detail == null ? "" : " (" + best.detail + ")"));
            }
        }

        return report;
    }

    private static string FirstDiscriminatorValue(DbContext ctx)
    {
        foreach (var entityType in ctx.Model.GetEntityTypes())
        {
            if (entityType.FindDiscriminatorProperty() != null
                && entityType.GetDiscriminatorValue() is string value
                && value.Length > 0)
            {
                return value;
            }
        }

        return null;
    }

    public static Exception Unwrap(Exception ex) =>
        ex is TargetInvocationException invocation && invocation.InnerException != null
            ? Unwrap(invocation.InnerException)
            : ex;

    // Only names declared by PreviewErrorKind may be emitted; anything finer goes into `detail`.
    public static string Classify(Exception ex)
    {
        var message = ex.Message ?? "";
        if (message.Contains("could not be translated")) return "NotTranslatable";
        if (ex is MissingMethodException || ex is TypeLoadException || ex is System.IO.FileNotFoundException)
            return "ProviderVersionMismatch";
        if (ex is DbException) return "ProviderError";
        return "Unknown";
    }

    public static string Detail(Exception ex)
    {
        var message = ex.Message ?? "";
        if (message.Contains("No discriminators matched") || message.Contains("JSON object was expected"))
            return "SyntheticRowRejected";
        if (message.Contains("Sequence contains no elements")) return "EmptyResultSet";
        if (message.Contains("doesn't have as many fields")) return "ReaderTooNarrow";
        return null;
    }

    public static string ProviderShortName(string assemblyName) => assemblyName switch
    {
        "Microsoft.EntityFrameworkCore.SqlServer" => "SqlServer",
        "Microsoft.EntityFrameworkCore.Sqlite" => "Sqlite",
        "Npgsql.EntityFrameworkCore.PostgreSQL" => "PostgreSql",
        "Pomelo.EntityFrameworkCore.MySql" => "MySql",
        "MySql.EntityFrameworkCore" => "MySql",
        "Oracle.EntityFrameworkCore" => "Oracle",
        _ => "Unknown",
    };

    private static string Sanitize(string connectionString)
    {
        if (string.IsNullOrEmpty(connectionString)) return connectionString;
        var parts = connectionString.Split(';');
        for (int i = 0; i < parts.Length; i++)
        {
            var pair = parts[i].Split(new[] { '=' }, 2);
            if (pair.Length == 2)
            {
                var key = pair[0].Trim().ToLowerInvariant();
                if (key == "password" || key == "pwd") parts[i] = pair[0] + "=***";
            }
        }

        return string.Join(";", parts);
    }

    private sealed class Rung
    {
        public Rung(string name, int rows, string stringValue) { Name = name; Rows = rows; StringValue = stringValue; }
        public string Name;
        public int Rows;
        public string StringValue;
    }

    private sealed class Attempt
    {
        public string rung, error, errorKind, detail;
        public ResultInfo result;
        public List<CapturedCommand> commands = new();
    }
}

public sealed class Probe
{
    // Verified: 8 is too narrow for a ten-column split query, int.MaxValue throws OutOfMemoryException.
    public const int WideFieldCount = 1024;

    public int Rows = 1;
    public string StringValue = "";
    public IModel Model;
    public readonly List<CapturedCommand> Captured = new();

    public FakeReader NewReader() => new FakeReader(WideFieldCount, Rows, StringValue);

    public async Task<ResultInfo> ObserveAsync<T>(Func<Task<T>> f) => Describe(typeof(T), await f(), true);

    public ResultInfo Observe<T>(Func<T> f) => Describe(typeof(T), f(), false);

    public async Task<ResultInfo> ObserveVoidAsync(Func<Task> f) { await f(); return Describe(typeof(void), null, true); }

    public ResultInfo ObserveVoid(Action f) { f(); return Describe(typeof(void), null, false); }

    // A selection with no terminal operator emits no SQL until something enumerates it.
    public ResultInfo ObserveDeferred<T>(Func<IQueryable<T>> f)
    {
        var q = f();
        foreach (var _ in q) { }
        return Describe(typeof(IQueryable<T>), q, false);
    }

    public ResultInfo ObserveEnumerable<T>(Func<IEnumerable<T>> f)
    {
        var q = f();
        foreach (var _ in q) { }
        return Describe(typeof(IEnumerable<T>), q, false);
    }

    public async Task<ResultInfo> ObserveAsyncEnumerable<T>(Func<IAsyncEnumerable<T>> f)
    {
        var q = f();
        await foreach (var _ in q) { }
        return Describe(typeof(IAsyncEnumerable<T>), q, true);
    }

    private ResultInfo Describe(Type declared, object value, bool isAsync)
    {
        var info = new ResultInfo
        {
            isAsync = isAsync,
            declaredResultType = Pretty(declared),
            runtimeResultType = value == null ? null : Pretty(value.GetType()),
        };

        var t = declared;
        var element = t;

        if (t == typeof(void)) { info.shape = "Void"; info.elementType = null; info.elementKind = null; return info; }
        if (t == typeof(bool)) info.shape = "Boolean";
        else if (Is(t, typeof(List<>)) || Is(t, typeof(IList<>)) || Is(t, typeof(IReadOnlyList<>)) || Is(t, typeof(ICollection<>)))
        { info.shape = "List"; element = t.GetGenericArguments()[0]; }
        else if (t.IsArray) { info.shape = "Array"; element = t.GetElementType(); }
        else if (Is(t, typeof(Dictionary<,>)) || Is(t, typeof(IDictionary<,>)) || Is(t, typeof(IReadOnlyDictionary<,>)))
        { info.shape = "Dictionary"; info.keyType = Pretty(t.GetGenericArguments()[0]); element = t.GetGenericArguments()[1]; }
        else if (Is(t, typeof(HashSet<>)) || Is(t, typeof(ISet<>))) { info.shape = "HashSet"; element = t.GetGenericArguments()[0]; }
        else if (Is(t, typeof(ILookup<,>))) { info.shape = "Lookup"; info.keyType = Pretty(t.GetGenericArguments()[0]); element = t.GetGenericArguments()[1]; }
        else if (Is(t, typeof(IQueryable<>))) { info.shape = "DeferredQueryable"; element = t.GetGenericArguments()[0]; }
        else if (Is(t, typeof(IEnumerable<>))) { info.shape = "DeferredEnumerable"; element = t.GetGenericArguments()[0]; }
        else if (Is(t, typeof(IAsyncEnumerable<>))) { info.shape = "AsyncEnumerable"; element = t.GetGenericArguments()[0]; }
        else if (IsScalar(t)) info.shape = "Scalar";
        else info.shape = "SingleElement";

        info.elementType = Pretty(element);
        info.elementKind = KindOf(element);
        return info;
    }

    private static bool Is(Type t, Type definition) => t.IsGenericType && t.GetGenericTypeDefinition() == definition;

    private static bool IsScalar(Type t)
    {
        var u = Nullable.GetUnderlyingType(t) ?? t;
        return u.IsPrimitive || u.IsEnum || u == typeof(string) || u == typeof(decimal) || u == typeof(DateTime)
            || u == typeof(DateTimeOffset) || u == typeof(DateOnly) || u == typeof(TimeOnly) || u == typeof(TimeSpan)
            || u == typeof(Guid) || u == typeof(byte[]);
    }

    // context.Model.FindEntityType is the only reliable entity-versus-DTO oracle available at runtime.
    private string KindOf(Type t)
    {
        var u = Nullable.GetUnderlyingType(t) ?? t;
        if (IsScalar(u)) return "Scalar";
        if (Model != null && Model.FindEntityType(u) != null) return "Entity";
        if (u.IsGenericType && u.Name.Contains("AnonymousType")) return "Anonymous";
        if (u.IsGenericType && u.GetGenericTypeDefinition().Name.StartsWith("ValueTuple")) return "Tuple";
        if (u.IsGenericType && u.GetGenericTypeDefinition().Name.StartsWith("IGrouping")) return "Grouping";
        return "Dto";
    }

    public static string Pretty(Type t)
    {
        if (t == null) return null;
        var nullable = Nullable.GetUnderlyingType(t);
        if (nullable != null) return Pretty(nullable) + "?";
        if (t.IsArray) return Pretty(t.GetElementType()) + "[]";
        if (!t.IsGenericType) return Alias(t);
        var name = t.Name;
        var tick = name.IndexOf('`');
        if (tick > 0) name = name.Substring(0, tick);
        if (t.Name.Contains("AnonymousType")) name = "anonymous";
        return name + "<" + string.Join(", ", t.GetGenericArguments().Select(Pretty)) + ">";
    }

    private static string Alias(Type t) => t.FullName switch
    {
        "System.Int32" => "int",
        "System.Int64" => "long",
        "System.Int16" => "short",
        "System.Boolean" => "bool",
        "System.String" => "string",
        "System.Decimal" => "decimal",
        "System.Double" => "double",
        "System.Single" => "float",
        "System.Byte" => "byte",
        "System.Object" => "object",
        "System.Void" => "void",
        _ => t.Name,
    };
}

public static class ContextActivator
{
    public static DbContext Create(Type ctxType, CaptureInterceptor interceptor, Report report)
    {
        // A generated subclass exposes a static Pending field; it is the only way to reach a context that
        // picks its provider in OnConfiguring and has no DbContextOptions constructor to rebuild from.
        var pending = ctxType.GetField("Pending", BindingFlags.Public | BindingFlags.Static);
        if (pending != null && pending.FieldType == typeof(CaptureInterceptor))
        {
            pending.SetValue(null, interceptor);
            report.activationStrategy = "DerivedOnConfiguringContext";
            if (Preview.Dialect != null)
            {
                report.warnings.Add("This DbContext selects its provider in OnConfiguring, so the dialect picker cannot override it.");
            }

            return (DbContext)Activator.CreateInstance(ctxType);
        }

        // The design-time factory hard-codes a provider, so the dialect picker has to bypass it.
        if (Preview.Dialect == null)
        {
            var factoryInterface = typeof(IDesignTimeDbContextFactory<>).MakeGenericType(ctxType);
            var factoryType = AllTypes().FirstOrDefault(t => !t.IsAbstract && !t.IsInterface && factoryInterface.IsAssignableFrom(t));
            if (factoryType != null)
            {
                try
                {
                    var factory = Activator.CreateInstance(factoryType);
                    var produced = (DbContext)factoryInterface.GetMethod("CreateDbContext").Invoke(factory, new object[] { Array.Empty<string>() });
                    var rebuilt = Rebuild(produced, ctxType, interceptor);
                    produced.Dispose();
                    if (rebuilt != null) { report.activationStrategy = "DesignTimeFactory"; return rebuilt; }
                }
                catch (Exception ex)
                {
                    report.warnings.Add("IDesignTimeDbContextFactory failed: " + Preview.Unwrap(ex).Message);
                }
            }
        }

        DbContextOptions options;
        try { options = BuildOptions(ctxType, interceptor); }
        catch (Exception ex) { throw new PreviewActivationException(ctxType, Preview.Unwrap(ex)); }

        var ctors = ctxType.GetConstructors(BindingFlags.Public | BindingFlags.Instance | BindingFlags.NonPublic)
                           .OrderBy(c => c.GetParameters().Length).ToArray();

        var exact = ctors.FirstOrDefault(c => c.GetParameters().Length == 1 && c.GetParameters()[0].ParameterType.IsInstanceOfType(options));
        if (exact != null)
        {
            report.activationStrategy = "OptionsConstructor";
            try { return (DbContext)exact.Invoke(new object[] { options }); }
            catch (Exception ex) { throw new PreviewActivationException(ctxType, Preview.Unwrap(ex)); }
        }

        var withOptions = ctors.FirstOrDefault(c => c.GetParameters().Any(p => p.ParameterType.IsInstanceOfType(options)));
        if (withOptions != null)
        {
            var parameters = withOptions.GetParameters();
            var arguments = parameters.Select(p => p.ParameterType.IsInstanceOfType(options) ? options : Stub.Make(p.ParameterType)).ToArray();
            report.activationStrategy = "OptionsConstructorWithStubbedDependencies";
            var extras = parameters.Where(p => !p.ParameterType.IsInstanceOfType(options)).Select(p => p.ParameterType.Name).ToArray();
            if (extras.Length > 0)
            {
                report.warnings.Add("The DbContext constructor also requires " + string.Join(", ", extras) + "; stub instances were supplied.");
            }

            try { return (DbContext)withOptions.Invoke(arguments); }
            catch (Exception ex) { throw new PreviewActivationException(ctxType, Preview.Unwrap(ex)); }
        }

        throw new PreviewActivationException(ctxType, new InvalidOperationException("No DbContextOptions constructor was found."));
    }

    private static DbContextOptions BuildOptions(Type ctxType, CaptureInterceptor interceptor)
    {
        var builderType = typeof(DbContextOptionsBuilder<>).MakeGenericType(ctxType);
        var builder = (DbContextOptionsBuilder)Activator.CreateInstance(builderType);
        Preview.ConfigureProvider(builder);
        builder.AddInterceptors(interceptor);
        builder.ConfigureWarnings(w => w.Ignore(CoreEventId.ManyServiceProvidersCreatedWarning));

        // DbContextOptionsBuilder<T>.Options hides the base member, so reflecting on "Options" throws
        // AmbiguousMatchException; the base property already returns DbContextOptions<T>.
        return builder.Options;
    }

    private static DbContext Rebuild(DbContext existing, Type ctxType, CaptureInterceptor interceptor)
    {
        try
        {
            var resolved = existing.GetService<IDbContextOptions>();
            var builderType = typeof(DbContextOptionsBuilder<>).MakeGenericType(ctxType);
            var builder = (DbContextOptionsBuilder)Activator.CreateInstance(builderType, resolved);
            builder.AddInterceptors(interceptor);
            builder.ConfigureWarnings(w => w.Ignore(CoreEventId.ManyServiceProvidersCreatedWarning));
            var options = builder.Options;
            var ctor = ctxType.GetConstructors()
                .FirstOrDefault(c => c.GetParameters().Length == 1 && c.GetParameters()[0].ParameterType.IsInstanceOfType(options));
            return ctor == null ? null : (DbContext)ctor.Invoke(new object[] { options });
        }
        catch
        {
            return null;
        }
    }

    public static IEnumerable<Type> AllTypes()
    {
        LoadNeighbouringAssemblies();
        return AppDomain.CurrentDomain.GetAssemblies()
            .Where(a => !a.IsDynamic)
            .SelectMany(a => { try { return a.GetTypes(); } catch { return Array.Empty<Type>(); } });
    }

    // Referenced assemblies load lazily, so a design-time factory in a project whose types the query never
    // mentions would otherwise be invisible.
    public static void LoadNeighbouringAssemblies()
    {
        try
        {
            var baseDirectory = AppContext.BaseDirectory;
            if (string.IsNullOrEmpty(baseDirectory)) return;
            foreach (var file in System.IO.Directory.GetFiles(baseDirectory, "*.dll"))
            {
                try { Assembly.LoadFrom(file); } catch { }
            }
        }
        catch { }
    }
}

public sealed class PreviewActivationException : Exception
{
    public PreviewActivationException(Type type, Exception inner)
        : base("Could not construct '" + type.FullName + "': " + inner.Message
               + " Add an IDesignTimeDbContextFactory<" + type.Name + "> to the project -- the same hook `dotnet ef` uses -- "
               + "and EF Core SQL Preview will use it.", inner)
    {
    }
}

public static class Stub
{
    // Passing null for a constructor's other dependencies is not enough: a context that reads a property off
    // an injected service throws NullReferenceException before EF is ever reached.
    public static object Make(Type t)
    {
        if (t.IsValueType) return Activator.CreateInstance(t);
        if (t == typeof(string)) return "";
        if (t.IsInterface)
        {
            try
            {
                var create = typeof(DispatchProxy).GetMethods(BindingFlags.Public | BindingFlags.Static)
                    .First(m => m.Name == "Create" && m.IsGenericMethodDefinition && m.GetGenericArguments().Length == 2);
                return create.MakeGenericMethod(t, typeof(NullProxy)).Invoke(null, Array.Empty<object>());
            }
            catch { return null; }
        }

        if (!t.IsAbstract)
        {
            try { return Activator.CreateInstance(t, nonPublic: true); } catch { }
        }

        return null;
    }
}

public class NullProxy : DispatchProxy
{
    protected override object Invoke(MethodInfo method, object[] arguments)
    {
        var returnType = method.ReturnType;
        if (returnType == typeof(void)) return null;
        if (returnType == typeof(string)) return "";
        if (returnType.IsValueType) return Activator.CreateInstance(returnType);
        return null;
    }
}

public sealed class CaptureInterceptor : DbConnectionInterceptor, IDbCommandInterceptor
{
    private readonly Probe _probe;

    public CaptureInterceptor(Probe probe) => _probe = probe;

    public override InterceptionResult ConnectionOpening(DbConnection c, ConnectionEventData e, InterceptionResult r) => InterceptionResult.Suppress();
    public override ValueTask<InterceptionResult> ConnectionOpeningAsync(DbConnection c, ConnectionEventData e, InterceptionResult r, CancellationToken ct = default) => new(InterceptionResult.Suppress());
    public override InterceptionResult ConnectionClosing(DbConnection c, ConnectionEventData e, InterceptionResult r) => InterceptionResult.Suppress();
    public override ValueTask<InterceptionResult> ConnectionClosingAsync(DbConnection c, ConnectionEventData e, InterceptionResult r) => new(InterceptionResult.Suppress());

    public InterceptionResult<DbDataReader> ReaderExecuting(DbCommand c, CommandEventData e, InterceptionResult<DbDataReader> r)
    { Capture(c); return InterceptionResult<DbDataReader>.SuppressWithResult(_probe.NewReader()); }

    public ValueTask<InterceptionResult<DbDataReader>> ReaderExecutingAsync(DbCommand c, CommandEventData e, InterceptionResult<DbDataReader> r, CancellationToken ct = default)
    { Capture(c); return new(InterceptionResult<DbDataReader>.SuppressWithResult(_probe.NewReader())); }

    public InterceptionResult<int> NonQueryExecuting(DbCommand c, CommandEventData e, InterceptionResult<int> r)
    { Capture(c); return InterceptionResult<int>.SuppressWithResult(0); }

    public ValueTask<InterceptionResult<int>> NonQueryExecutingAsync(DbCommand c, CommandEventData e, InterceptionResult<int> r, CancellationToken ct = default)
    { Capture(c); return new(InterceptionResult<int>.SuppressWithResult(0)); }

    public InterceptionResult<object> ScalarExecuting(DbCommand c, CommandEventData e, InterceptionResult<object> r)
    { Capture(c); return InterceptionResult<object>.SuppressWithResult(null); }

    public ValueTask<InterceptionResult<object>> ScalarExecutingAsync(DbCommand c, CommandEventData e, InterceptionResult<object> r, CancellationToken ct = default)
    { Capture(c); return new(InterceptionResult<object>.SuppressWithResult(null)); }

    private void Capture(DbCommand command)
    {
        var captured = new CapturedCommand { sql = Normalize(command.CommandText), commandType = command.CommandType.ToString() };
        foreach (DbParameter p in command.Parameters)
        {
            var isNull = p.Value is null || p.Value == DBNull.Value;
            captured.parameters.Add(new CapturedParameter
            {
                name = p.ParameterName,
                dbType = SafeDbType(p),
                clrType = isNull ? null : Probe.Pretty(p.Value.GetType()),
                value = ValueRenderer.Render(p.Value),
                isNull = isNull,
                size = p.Size,
                direction = p.Direction.ToString(),
            });
        }

        _probe.Captured.Add(captured);
    }

    private static string SafeDbType(DbParameter p)
    {
        try { return p.DbType.ToString(); } catch { return null; }
    }

    // EF emits CRLF on Windows; normalising makes the tool window line-ending agnostic. Nothing else is
    // reformatted: EF's own layout is already readable and re-flowing risks mangling string literals.
    private static string Normalize(string sql) => sql?.Replace("\r\n", "\n").Replace("\r", "\n").Trim();
}

public static class ValueRenderer
{
    public static string Render(object v)
    {
        if (v is null || v == DBNull.Value) return null;
        switch (v)
        {
            case string s: return s;
            case bool b: return b ? "true" : "false";
            case byte[] bytes:
                var head = bytes.Length > 32 ? bytes.AsSpan(0, 32).ToArray() : bytes;
                return "0x" + Convert.ToHexString(head) + (bytes.Length > 32 ? "…" : "");
            case DateTime dt: return dt.ToString("O", CultureInfo.InvariantCulture);
            case DateTimeOffset dto: return dto.ToString("O", CultureInfo.InvariantCulture);
            // Npgsql sends a whole collection as a single array parameter rather than expanding it.
            case IEnumerable e: return "[" + string.Join(", ", e.Cast<object>().Take(64).Select(Render)) + "]";
            default: return Convert.ToString(v, CultureInfo.InvariantCulture);
        }
    }
}

